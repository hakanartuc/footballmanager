// Embeds lib/src/data/assets/**.json into lib/src/data/assets_embedded.dart
// so the engine can load them without file IO (web).
//
// Run from anywhere: dart run tool/embed_assets.dart
import 'dart:io';

void main() {
  final root = File.fromUri(Platform.script).parent.parent;
  final dir = Directory('${root.path}/lib/src/data/assets');
  final files =
      dir
          .listSync(recursive: true)
          .whereType<File>()
          .where((f) => f.path.endsWith('.json'))
          .toList()
        ..sort((a, b) => a.path.compareTo(b.path));

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/embed_assets.dart. Do not edit by hand.')
    ..writeln()
    ..writeln('const Map<String, String> embeddedAssets = {');
  for (final f in files) {
    final key = f.path
        .substring(dir.path.length + 1)
        .replaceAll(Platform.pathSeparator, '/');
    final text = f.readAsStringSync();
    if (text.contains("'''")) {
      throw StateError("$key contains ''' and cannot be embedded");
    }
    out.write("  '$key': r'''\n$text''',\n");
  }
  out.writeln('};');

  File(
    '${root.path}/lib/src/data/assets_embedded.dart',
  ).writeAsStringSync(out.toString());
  stdout.writeln('Embedded ${files.length} assets.');
}
